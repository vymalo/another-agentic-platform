//! The operator: the composition root (AD-020). `crdgen` prints the CRDs; `run` reads one configuration file
//! (`config.example.yaml` documents every key), composes the Kubernetes runtime provider, the store (CloudNativePG, or
//! referenced Secrets) and the controllers, and serves health, metrics and, with a token, the agent registry.
//!
//! `operator run --check` reads the file, says whether the operator can work with it, and exits: 0 when it can, 78
//! (`EX_CONFIG`) when it is refused, and 1 for anything else.

mod config;
mod run;
#[cfg(feature = "runtime-kubernetes")]
mod serve;

use std::io::{self, Write};
use std::path::PathBuf;
use std::process::ExitCode;

use anyhow::{Context, Result};
use clap::{Parser, Subcommand};

/// The another-agentic-platform operator.
#[derive(Debug, Parser)]
#[command(name = "operator", version, about)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Print the CustomResourceDefinitions as multi-document YAML.
    Crdgen,
    /// Print the JSON Schema of the configuration file (ANR-962), as `bin/operator/config.schema.json` holds it.
    Schema,
    /// Run the controllers: reconcile AgentService and AgentConfig objects.
    Run(RunArgs),
}

/// The settings of `run`: where the file is, and whether to stop after reading it.
#[derive(Debug, clap::Args)]
struct RunArgs {
    /// The configuration file (`config.example.yaml` documents every key).
    #[arg(long, default_value = config::DEFAULT_PATH)]
    config: PathBuf,

    /// Read the configuration file, say whether the operator can work with it, and exit. Needs no cluster and reads no
    /// file the configuration names (a Secret is mounted in the pod, not on the machine that checks a chart).
    #[arg(long)]
    check: bool,
}

fn main() -> ExitCode {
    match real_main(Cli::parse()) {
        Ok(code) => code,
        Err(err) => {
            eprintln!("operator: {err:#}");
            ExitCode::FAILURE
        }
    }
}

fn real_main(cli: Cli) -> Result<ExitCode> {
    match cli.command {
        Command::Crdgen => {
            crdgen(&mut io::stdout().lock())?;
            Ok(ExitCode::SUCCESS)
        }
        Command::Schema => {
            print!("{}", config::schema()?);
            Ok(ExitCode::SUCCESS)
        }
        Command::Run(args) => {
            // The file is the only way in (ANR-962): without it there is nothing to run. A file that is refused is
            // `EX_CONFIG` (78), and one that cannot be read (missing, a directory, no permission) is 1, so that a deployment
            // and a script can tell the author's mistake from a pod whose mount is wrong.
            let settings = match config::load(&args.config) {
                Ok(settings) => settings,
                Err(err) => {
                    eprintln!("operator: {err:#}");
                    return Ok(ExitCode::from(err.exit_code()));
                }
            };
            if args.check {
                println!("{}: ok", args.config.display());
                return Ok(ExitCode::SUCCESS);
            }
            tracing_subscriber::fmt()
                .with_env_filter(
                    tracing_subscriber::EnvFilter::try_new(&settings.log_filter)
                        .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new("info")),
                )
                .with_writer(io::stderr)
                .init();
            let result = tokio::runtime::Builder::new_multi_thread()
                .enable_all()
                .build()
                .context("starting the async runtime")?
                .block_on(run::run(settings));
            // A reference the file names that gives nothing (a token file that is missing or empty) is the file refused: 78.
            if let Err(err) = &result
                && config::is_reference_refused(err)
            {
                eprintln!("operator: {err:#}");
                return Ok(ExitCode::from(config::EXIT_CONFIG));
            }
            result?;
            Ok(ExitCode::SUCCESS)
        }
    }
}

/// Header of the generated file. `deploy/crds/agents.vymalo.com.yaml` starts with it.
const HEADER: &str = "# Generated by `cargo run -p aap-operator -- crdgen`. Do not edit.\n\
                      # CI fails when this file differs from the output of the command.\n";

/// Write the CRDs of `aap-api` as one YAML document each.
fn crdgen(out: &mut impl Write) -> Result<()> {
    out.write_all(HEADER.as_bytes())?;
    for crd in aap_api::crds() {
        out.write_all(b"---\n")?;
        let yaml = serde_yaml::to_string(&crd).context("serialising a CRD to YAML")?;
        out.write_all(yaml.as_bytes())?;
    }
    out.flush()?;
    Ok(())
}
