//! The operator: the composition root (AD-020). Today it prints the CRDs (`crdgen`); the
//! controller (`run`) arrives with slice S5.

use std::io::{self, Write};
use std::process::ExitCode;

use anyhow::{Context, Result, bail};
use clap::{Parser, Subcommand};

/// The another-agentic-platform operator.
#[derive(Debug, Parser)]
#[command(name = "operator", version, about)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Print the CustomResourceDefinitions as multi-document YAML.
    Crdgen,
    /// Run the controller. Not implemented until slice S5.
    Run,
}

fn main() -> ExitCode {
    match real_main(Cli::parse()) {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("operator: {err:#}");
            ExitCode::FAILURE
        }
    }
}

fn real_main(cli: Cli) -> Result<()> {
    match cli.command {
        Command::Crdgen => crdgen(&mut io::stdout().lock()),
        Command::Run => bail!(
            "`operator run` is not implemented until slice S5 (the controller); \
             this build only has `operator crdgen`"
        ),
    }
}

/// Header of the generated file. `deploy/crds/agents.vymalo.com.yaml` starts with it.
const HEADER: &str = "# Generated by `cargo run -p aap-operator -- crdgen`. Do not edit.\n\
                      # CI fails when this file differs from the output of the command.\n";

/// Write the CRDs of `aap-api` as one YAML document each.
fn crdgen(out: &mut impl Write) -> Result<()> {
    out.write_all(HEADER.as_bytes())?;
    for crd in aap_api::crds() {
        out.write_all(b"---\n")?;
        let yaml = serde_yaml::to_string(&crd).context("serialising a CRD to YAML")?;
        out.write_all(yaml.as_bytes())?;
    }
    out.flush()?;
    Ok(())
}
