#!/usr/bin/env python3
"""Writes deploy/dashboards/api.json. The series are those of crates/platform-api/src/metrics.rs."""

import sys

if __name__ == "__main__":
    # A neighbour is named like a standard library module: see grafana.py.
    del sys.path[0]
sys.dont_write_bytecode = True

import importlib.util
from pathlib import Path

_spec = importlib.util.spec_from_file_location("dashboard_grafana", Path(__file__).resolve().with_name("grafana.py"))
g = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(g)

NAME = "api"


def build():
    panels = [
        g.timeseries(
            "Requests, by route",
            [g.target("sum by (route) (rate(aap_api_requests_total[5m]))", "{{route}}")],
            "The route is a template of the API's route table, or `unmatched`.",
            unit="reqps",
        ),
        g.timeseries(
            "Requests, by status",
            [g.target("sum by (status) (rate(aap_api_requests_total[5m]))", "{{status}}")],
            unit="reqps",
        ),
        g.timeseries(
            "Share of requests answered with a 5xx",
            [
                g.target(
                    'sum(rate(aap_api_requests_total{status=~"5.."}[5m])) / sum(rate(aap_api_requests_total[5m]))',
                    "5xx",
                )
            ],
            "No data until a request has been answered with a 5xx.",
            unit="percentunit",
        ),
        g.timeseries(
            "Authentication failures, by reason",
            [g.target("sum by (reason) (rate(aap_api_auth_failures_total[5m]))", "{{reason}}")],
            "Tokens and certificates that were refused or could not be checked. A reason that starts with `cert_` is "
            "the workload listener's.",
            unit="reqps",
        ),
    ]
    return g.dashboard(
        "aap-platform-api",
        "Agent platform: Platform API",
        "The Platform API's counters. A series appears the first time it is counted, so a panel with nothing to show "
        "says No data. Generated by tools/dashboards/api.py; do not edit the JSON.",
        panels,
    )


if __name__ == "__main__":
    g.write(NAME, build())
