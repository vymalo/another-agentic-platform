#!/usr/bin/env python3
"""Writes deploy/dashboards/operator.json. The series are those of crates/controller/src/metrics.rs."""

import sys

sys.dont_write_bytecode = True

import grafana as g

NAME = "operator"


def rate(title, expr, legend="", description="", **kwargs):
    return g.timeseries(title, [g.target(expr, legend)], description, **kwargs)


def total_in_range(title, series, description):
    return g.stat(title, [g.target(f"sum(increase({series}[$__range]))", instant=True)], description)


def build():
    panels = [
        rate(
            "Reconcile passes, by controller and result",
            "sum by (controller, result) (rate(aap_reconcile_total[5m]))",
            "{{controller}} {{result}}",
        ),
        rate(
            "Failed passes, by controller and class",
            "sum by (controller, class) (rate(aap_reconcile_errors_total[5m]))",
            "{{controller}} {{class}}",
        ),
        rate(
            "Passes cut short, by controller",
            "sum by (controller) (rate(aap_reconcile_timeouts_total[5m]))",
            "{{controller}}",
            "Passes that took longer than the pass timeout.",
            width=8,
        ),
        rate("Status patches", "sum(rate(aap_status_patches_total[5m]))", "patches", width=8),
        rate(
            "Runtime signals",
            "sum(rate(aap_runtime_signals_total[5m]))",
            "signals",
            "Ids heard from the runtime provider's watch. Every replica counts them.",
            width=8,
        ),
        g.stat(
            "Service state changes in the time range, by new state",
            [g.target("sum by (state) (increase(aap_service_state_changes_total[$__range]))", "{{state}}", instant=True)],
            "How often a service changed into each state. It is not the number of services in a state now.",
            width=24,
        ),
        total_in_range(
            "Services deleted in the time range",
            "aap_services_deleted_total",
            "Services whose workload and store the finalizer released.",
        ),
        total_in_range(
            "Retention purges in the time range",
            "aap_retention_purged_total",
            "Retained databases and volumes the retention sweep deleted.",
        ),
        g.stat(
            "Agent sleeps counted by the running pods",
            [g.target("sum(aap_agent_sleeps_total)", instant=True)],
            "Scale-downs to zero since each pod started. It is not the number of agents asleep now, and it starts again "
            "at 0 when a pod restarts.",
            width=12,
        ),
        g.note(
            "Leader changes are not on this dashboard",
            "The election counts its changes in `leaseTransitions`, a field of the `Lease` object. It is not a "
            "Prometheus series, so there is no panel for it. Read the `Lease` with `kubectl`.",
        ),
        rate("Meter: lines handed to the sink", "sum(rate(aap_meter_events_total[5m]))", "events"),
        rate(
            "Meter: pod-minutes with no line, by reason",
            "sum by (reason) (rate(aap_meter_unattributed_total[5m]))",
            "{{reason}}",
        ),
        rate("Meter: lines the sink refused to queue", "sum(rate(aap_meter_send_failures_total[5m]))", "failures", width=8),
        rate("Meter: lines the collector acknowledged", "sum(rate(aap_meter_delivered_total[5m]))", "delivered", width=8),
        rate("Meter: lines the collector refused for good", "sum(rate(aap_meter_refused_total[5m]))", "refused", width=8),
        g.timeseries(
            "Meter: tombstones",
            [
                g.target(f"sum(rate(aap_meter_tombstones_{kind}_total[5m]))", kind)
                for kind in ("written", "released", "restored", "expired", "unbacked", "unreadable", "refused", "invalid")
            ],
            "The records that keep the minutes of a vanished pod until they are acknowledged.",
        ),
        rate(
            "Meter: failed tombstone store calls, by op",
            "sum by (op) (rate(aap_meter_tombstone_errors_total[5m]))",
            "{{op}}",
        ),
    ]
    return g.dashboard(
        "aap-operator",
        "Agent platform: operator",
        "The operator's counters. A series appears the first time it is counted, so a panel with nothing to show says "
        "No data. There is no leader-change panel: leaseTransitions is a field of the Lease, not a Prometheus series. "
        "Generated by tools/dashboards/operator_dashboard.py; do not edit the JSON.",
        panels,
    )


if __name__ == "__main__":
    g.write(NAME, build())
